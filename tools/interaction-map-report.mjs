// ./tools/interaction-map-report.mjs
// Markdown rendering for the source-derived interaction inventory and task
// click-budget report.

import { shortText } from "./interaction-map-ast.mjs";

function markdownEscape(value) {
  return String(value ?? "").replace(/\|/gu, "\\|").replace(/\n/gu, " ");
}

function code(value) {
  return `\`${String(value ?? "").replaceAll("`", "'")}\``;
}

function link(root, line, label = `${root}:${line}`) {
  return `[${markdownEscape(label)}](../${root}#L${line})`;
}

function destinationText(targets) {
  return targets.length ? targets.map((target) => `${target.kind}:${target.value}${target.confidence === "static" ? "" : ` (${target.confidence})`}`).join("<br>") : "—";
}

export function renderMarkdown(report) {
  const out = [];
  out.push("# Interaction and click-flow map", "", "<!-- GENERATED by tools/interaction-map.mjs — do not edit by hand. -->", "<!-- Edit docs/interaction-tasks.json for task journeys, then run: node tools/interaction-map.mjs -->", "");
  out.push("This is a source-derived map of the Svelte desktop UI. It counts template controls, traces their handlers through local functions and component callback bindings, and records page, native-command, native-dialog, modal, external-link, and callback destinations. A template control inside an `{#each}` block is counted once; runtime repetition is shown in its guard column.", "");
  out.push("Static wiring is evidence of the path in source. It is not proof that a native picker, Tauri window, provider, real media run, or conditional branch works at runtime; those limits are called out below.", "");
  out.push("## Snapshot", "", "| Measure | Count |", "|---|---:|", `| Svelte files scanned | ${report.summary.files} |`, `| Template controls | ${report.summary.controls} |`, `| Buttons | ${report.summary.buttons} |`, `| Clickable controls | ${report.summary.clickable} |`, `| Click handlers | ${report.summary.clickEvents} |`, `| Links | ${report.summary.links} |`, `| Form controls | ${report.summary.formControls} |`, `| Disclosure controls | ${report.summary.disclosures} |`, `| Duplicate destination groups | ${report.summary.duplicateDestinations} |`, `| Repeated user-facing destination groups | ${report.summary.duplicateUserFacingDestinations} |`, `| Duplicate label groups | ${report.summary.duplicateLabels} |`, "");

  out.push("## Cardinal-rule task paths", "", "The task catalog compares declared candidate paths. `Minimum` is the shortest complete path in the catalog; `+N` marks excess click opportunities. Text entry, native picker choices, scrolling, and waiting are listed as notes but are not counted as clicks. A non-button interaction can declare an explicit `clicks` cost when the task requires a tap, such as a checkbox acknowledgment.", "");
  for (const task of report.tasks) {
    out.push(`### ${task.title ?? task.id}`, "", task.goal ? `${task.goal}` : "", "", "| Candidate path | Clicks | Delta from minimum | Status |", "|---|---:|---:|---|");
    for (const path of task.paths) {
      const delta = path.excessClicks == null ? "—" : path.excessClicks === 0 ? "shortest" : `+${path.excessClicks}`;
      const status = path.unresolved ? `unresolved: ${path.id}` : "mapped";
      out.push(`| ${markdownEscape(path.label ?? path.id)} | ${path.clicks} | ${delta} | ${status} |`);
    }
    if (task.notes?.length) out.push("", `Notes: ${task.notes.map(markdownEscape).join(" ")}`);
    out.push("");
  }
  if (!report.tasks.length) out.push("No task catalog was found. Add journeys to `docs/interaction-tasks.json`.\n");

  out.push("## Redundancy and over-tap hotspots", "", "These are not automatically defects. They are places where the same destination or label has multiple entry points and should be compared against the task paths above.", "");
  const controlById = new Map(report.controls.map((control) => [control.id, control]));
  const entryPoints = (ids) => ids.slice(0, 8).map((id) => {
    const control = controlById.get(id);
    return control ? link(control.file, control.line, `${control.file.split("/").at(-1)}:${control.line} ${shortText(control.label, 70)}`) : id;
  }).join("<br>") + (ids.length > 8 ? "<br>…" : "");
  out.push("### Repeated user-facing destinations", "", "Persistence, readback, and internal callback plumbing are retained in the JSON report and full traces, but this table filters them so the first pass stays focused on navigation, dialogs, callbacks, and user-triggered work.", "", "| Destination | Controls | Entry points |", "|---|---:|---|");
  for (const group of report.duplicateUserFacingDestinations.sort((a, b) => b.controls.length - a.controls.length || a.destination.localeCompare(b.destination)).slice(0, 40)) out.push(`| ${code(group.destination)} | ${group.controls.length} | ${entryPoints(group.controls)} |`);
  out.push("", "### Repeated labels", "", "| Label | Controls | Entry points |", "|---|---:|---|");
  for (const group of report.duplicateLabels.sort((a, b) => b.controls.length - a.controls.length || a.label.localeCompare(b.label)).slice(0, 40)) out.push(`| ${markdownEscape(group.label)} | ${group.controls.length} | ${entryPoints(group.controls)} |`);
  out.push("");

  out.push("## Full control inventory", "", "Every source control is listed below. `Trace` is the static handler call chain; `Destination` is the resolved high-signal endpoint.", "");
  const byFile = new Map();
  for (const control of report.controls) {
    if (!byFile.has(control.file)) byFile.set(control.file, []);
    byFile.get(control.file).push(control);
  }
  for (const [file, controls] of byFile) {
    out.push(`### ${code(file)}`, "", "| Source | Kind | Label | Event / trace | Destination | Guards |", "|---|---|---|---|---|---|");
    for (const control of controls) {
      const eventText = control.events.length
        ? control.events.map((event) => `${event.name}: ${event.expression ? code(event.expression) : "(implicit)"}`).join("<br>") + (control.trace.length ? `<br>${control.trace.map(code).join(" → ")}` : "")
        : control.href ? `href ${code(control.href)}` : "(implicit disclosure)";
      const source = link(control.file, control.line, `L${control.line}`);
      out.push(`| ${source} | ${control.kind} | ${markdownEscape(control.label)} | ${eventText} | ${destinationText(control.targets)} | ${markdownEscape(control.guards.join("; ") || "always")} |`);
    }
    out.push("");
  }

  out.push("## Evidence and limits", "", "- Source evidence: the Svelte compiler parsed every file under `desktop/src`, and the inventory records the exact file/line for every control.", "- Callback evidence: component props are followed through static parent bindings where the component name resolves to a local `.svelte` file.", "- Conditional evidence: `guards` show source conditions and loop templates; the report does not claim every branch was rendered.", "- Native boundary: `openDialog`, Tauri `invoke`, OS menus, drag/drop, window behavior, provider requests, and real-media execution still require the project’s native acceptance walkthrough.", "- Runtime repetition: controls inside queue/card loops are template controls; one card can create many runtime instances, so task testing should measure both per-item and bulk paths.", "");
  if (report.warnings.length) {
    out.push("## Map warnings", "", ...report.warnings.map((warning) => `- ${markdownEscape(warning)}`), "");
  }
  return `${out.join("\n").replace(/\n{3,}/gu, "\n\n").trimEnd()}\n`;
}
